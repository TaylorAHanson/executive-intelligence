"""The agent tray's backend: one chat turn, or an answer to a paused approval.

The caller's identity comes from `get_caller` (the Apps proxy headers), never
from the request body, so a browser cannot ask the agent to recall another
user's memory or continue another user's conversation. The call to the agent
carries the user's own token, so the agent's data tools run as that user. See
`services/agent.py`.

`context` is the section of the app the user is in. The agent picks its prompt
and tools from it (`executive-intelligence-agent/agent/contexts.py`), and falls
back to its default for an id it doesn't know. Each turn also carries that
context's admin settings, read here as the user (`services/agent_settings.py`).
"""
from typing import Literal, Optional
from uuid import UUID

from databricks.sdk import WorkspaceClient
from fastapi import APIRouter, Depends
from pydantic import BaseModel, Field

from middleware.auth import CallerIdentity, get_caller, get_user_token, get_workspace_client
from services import agent, agent_settings

router = APIRouter()

_CONTEXT_PATTERN = r"^[a-z0-9][a-z0-9-]{0,63}$"


class ChatRequest(BaseModel):
    #: Generated by the browser per conversation. Hashed with the caller's email
    #: before it reaches the agent, so it identifies nothing on its own.
    session_id: UUID
    context: str = Field(pattern=_CONTEXT_PATTERN)
    message: str = Field(min_length=1, max_length=8000)


class Decision(BaseModel):
    type: Literal["approve", "reject"]
    message: Optional[str] = Field(default=None, max_length=2000)


class ResumeRequest(BaseModel):
    session_id: UUID
    context: str = Field(pattern=_CONTEXT_PATTERN)
    #: One decision per tool call awaiting approval, in the order the agent listed them.
    decisions: list[Decision] = Field(min_length=1, max_length=20)


# `def`, not `async def`: the agent call blocks for up to AGENT_TIMEOUT_SECONDS,
# and FastAPI runs sync handlers in a thread pool so it delays only this request.
@router.post("/chat", summary="Send one turn to the agent as the signed-in user")
def chat(
    request: ChatRequest,
    caller: CallerIdentity = Depends(get_caller),
    user_token: Optional[str] = Depends(get_user_token),
    client: WorkspaceClient = Depends(get_workspace_client),
) -> dict:
    return agent.invoke(
        agent.invocation_body(
            session=agent.session_key(caller.email, str(request.session_id)),
            actor=caller.email,
            context=request.context,
            message=request.message,
            settings=agent_settings.for_context(client, request.context),
        ),
        user_token,
    )


@router.post("/resume", summary="Approve or reject the agent's paused tool calls")
def resume(
    request: ResumeRequest,
    caller: CallerIdentity = Depends(get_caller),
    user_token: Optional[str] = Depends(get_user_token),
    client: WorkspaceClient = Depends(get_workspace_client),
) -> dict:
    return agent.invoke(
        agent.resume_body(
            session=agent.session_key(caller.email, str(request.session_id)),
            actor=caller.email,
            context=request.context,
            decisions=[d.model_dump(exclude_none=True) for d in request.decisions],
            settings=agent_settings.for_context(client, request.context),
        ),
        user_token,
    )
